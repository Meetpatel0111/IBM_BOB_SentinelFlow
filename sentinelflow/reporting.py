"""
SentinelFlow - reporting.py
============================
Programmatic report generation for SentinelFlow analysis runs.

Produces:
  - A structured Python dict (report_data) as the single source of truth
  - An incident_report.json saved to outputs/
  - A Meet_ProjectReport.docx (built in Phase F via generate_docx())

All numerical values and text in the report are derived from actual
runtime objects — nothing is hardcoded or fabricated.
"""

