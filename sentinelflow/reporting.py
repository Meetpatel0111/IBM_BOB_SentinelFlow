# Report data builder
# ---------------------------------------------------------------------------

def build_report_data(
    df_events: pd.DataFrame,
    detections: list[Detection],
    incidents: list[Incident],
    scores: dict[str, float],
    manager: IncidentManager,
    eval_metrics: dict,
    actions: list[ContainmentAction],
    verifications: dict[str, list[VerificationResult]],
    run_timestamp: Optional[str] = None,
) -> dict:
    """Collect all analysis results into a single serialisable dict.

    This dict is the single source of truth shared between the JSON report,
    the Word document, and the notebook display cells.
    """
    if run_timestamp is None:
        run_timestamp = pd.Timestamp.now("UTC").isoformat()

    # --- dataset summary -------------------------------------------------
    n_total   = len(df_events)
    n_attack  = int(df_events["is_suspicious"].sum()) if "is_suspicious" in df_events.columns else 0
    n_benign  = n_total - n_attack

    # --- incident summary ------------------------------------------------
    mgr_df = manager.summary_dataframe()
    severity_dist = mgr_df["max_severity"].value_counts().to_dict() if not mgr_df.empty else {}
    score_stats = {}
    if not mgr_df.empty:
        sc = mgr_df["risk_score"]
        score_stats = {
            "min":    round(float(sc.min()), 2),
            "q25":    round(float(sc.quantile(0.25)), 2),
            "median": round(float(sc.median()), 2),
            "q75":    round(float(sc.quantile(0.75)), 2),
            "max":    round(float(sc.max()), 2),
        }

    top_incidents = []
    for _, row in mgr_df.head(10).iterrows():
        top_incidents.append({
            "incident_id":      row["incident_id"],
            "risk_score":       row["risk_score"],
            "max_severity":     row["max_severity"],
            "detection_types":  row["detection_types"],
            "username":         row["username"],
            "source_ip":        row["source_ip"],
            "event_count":      row["event_count"],
            "status":           row["status"],
        })

    # --- detection rule breakdown ----------------------------------------
    from collections import Counter
    rule_counts = Counter(d.rule_id for d in detections)

    # --- containment summary ---------------------------------------------
    n_executed = sum(1 for a in actions if a.status == "EXECUTED")
    n_rejected = sum(1 for a in actions if a.status == "REJECTED")
    n_failed   = sum(1 for a in actions if a.status == "FAILED")

    # --- verification summary --------------------------------------------
    all_ver = [v for vlist in verifications.values() for v in vlist]
    ver_success  = sum(1 for v in all_ver if v.outcome == "SUCCESS")
    ver_failed   = sum(1 for v in all_ver if v.outcome == "FAILED")
    ver_pending  = sum(1 for v in all_ver if v.outcome == "PENDING")
    ver_unverified = sum(1 for v in all_ver if v.outcome == "UNVERIFIED")

    return {
        "run_timestamp": run_timestamp,
        "project": {
            "title":  "SentinelFlow: Real-Time Detection and Automated Containment "
                      "of Suspicious Account Activity Using Python-Based SIEM Workflows",
            "author": "Riddhi Patel",
            "event":  "IBM SkillsBuild Cyber Security 2026 — BharatCares",
        },
        "dataset": {
            "path":          "data/synthetic_auth_logs.csv",
            "source":        "Synthetic — generated by sentinelflow/generate_dataset.py (seed=42)",
            "total_events":  n_total,
            "attack_events": n_attack,
            "benign_events": n_benign,
            "attack_pct":    round(n_attack / n_total * 100, 2) if n_total else 0,
            "scenarios":     ["benign", "brute_force", "cred_stuffing",
                              "off_hours_access", "lateral_movement"],
        },
        "detection": {
            "total_detections": len(detections),
            "rule_counts":      dict(rule_counts),
        },
        "evaluation": eval_metrics,
        "incidents": {
            "total":            len(incidents),
            "status_counts":    manager.count_by_status(),
            "severity_dist":    severity_dist,
            "score_stats":      score_stats,
            "top_10":           top_incidents,
        },
        "containment": {
            "total_actions": len(actions),
            "executed":      n_executed,
            "rejected":      n_rejected,
            "failed":        n_failed,
            "actions":       [a.to_dict() for a in actions],
        },
        "verification": {
            "total":      len(all_ver),
            "success":    ver_success,
            "failed":     ver_failed,
            "pending":    ver_pending,
            "unverified": ver_unverified,
            "results":    [v.to_dict() for v in all_ver],
        },
    }


# ---------------------------------------------------------------------------
# JSON report writer
# ---------------------------------------------------------------------------

def save_report_json(report_data: dict, path: str = REPORT_JSON) -> str:
    """Persist report_data to a JSON file and return the absolute path."""
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(report_data, fh, indent=2, default=str)
    return os.path.abspath(path)


