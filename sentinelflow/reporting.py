    from docx.oxml import OxmlElement
    import copy

    doc = Document()

    # ---- Page margins ----
    for section in doc.sections:
        section.top_margin    = Cm(2.5)
        section.bottom_margin = Cm(2.5)
        section.left_margin   = Cm(3.0)
        section.right_margin  = Cm(2.5)

    # ---- Helpers ----
    def add_heading(text, level=1):
        h = doc.add_heading(text, level=level)
        h.alignment = WD_ALIGN_PARAGRAPH.LEFT
        return h

    def add_para(text, bold=False, italic=False, size=11):
        p = doc.add_paragraph()
        run = p.add_run(text)
        run.bold   = bold
        run.italic = italic
        run.font.size = Pt(size)
        return p

    def add_kv(key, value):
        p = doc.add_paragraph()
        r1 = p.add_run(f"{key}: ")
        r1.bold = True
        p.add_run(str(value))

    def add_table_from_list(headers: list, rows: list):
        if not rows:
            doc.add_paragraph("(No data)")
            return
        table = doc.add_table(rows=1, cols=len(headers))
        table.style = "Table Grid"
        hdr = table.rows[0].cells
        for i, h in enumerate(headers):
            hdr[i].text = h
            for run in hdr[i].paragraphs[0].runs:
                run.bold = True
        for row in rows:
            cells = table.add_row().cells
            for i, val in enumerate(row):
                cells[i].text = str(val)
        doc.add_paragraph()

    proj   = report_data["project"]
    ds     = report_data["dataset"]
    det    = report_data["detection"]
    ev     = report_data["evaluation"]
    inc    = report_data["incidents"]
    cont   = report_data["containment"]
    ver    = report_data["verification"]
